def for_field(section: str, field: str) -> dict:
    """Людська назва поля. Немає запису — віддаємо машинне ім'я і
    «advanced»: краще показати як є, ніж вигадати переклад на льоту."""
    label, hint, level = L.get(f"{section}.{field}", (field, "", "advanced"))
    return {"label": label, "hint": hint, "level": level}


def decorate(schema: dict) -> dict:
    """Додати людські назви в схему, не чіпаючи технічних описів.

    Обидві мови їдуть поруч: `doc` лишається для агента й режиму
    «Експерт», `label`/`hint` — для панелі. Замінити одне іншим не можна:
    агент по «Прибрати жовтизну» не зрозуміє, що робити, а фотограф по
    «поріг перцентиля яскравості в межах класу» — тим паче.
    """
    for sec, fields in schema.get("sections", {}).items():
        for name, meta in fields.items():
            meta.update(for_field(sec, name))
    return schema


